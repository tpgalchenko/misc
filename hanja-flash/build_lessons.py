#!/usr/bin/env python3
"""
build_lessons.py

Packs all lesson files (l<N>.json, l<N>-<M>.json) into a single compressed data file
lessons.data.js loaded by index.html.

The lesson files are left untouched. Each one holds a single JSON object:

    { "name": "L23-2", "cards": [ ... ] }

The objects are collected into one array (ordered by lesson number), serialized as
minified JSON, gzip-compressed and stored base64-encoded:

    window.LESSONS_GZ = "...";

index.html decodes it with the browser's built-in DecompressionStream("gzip").

Usage:  python build_lessons.py [lesson_dir] [output_file]
Run it again after any change to the lesson files.
"""
import base64
import glob
import gzip
import json
import os
import re
import sys

LESSON_FILE = re.compile(r'^l(\d+)(?:-(\d+))?\.json$')


def lesson_files(lesson_dir):
    found = []
    for path in glob.glob(os.path.join(lesson_dir, 'l*.json')):
        m = LESSON_FILE.match(os.path.basename(path))
        if m:
            found.append(((int(m.group(1)), int(m.group(2) or 0)), path))
    return [path for _, path in sorted(found)]


def parse_lesson(path):
    with open(path, encoding='utf-8-sig') as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as e:
            raise ValueError(f'{path}: {e}') from None


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    lesson_dir = sys.argv[1] if len(sys.argv) > 1 else here
    output = sys.argv[2] if len(sys.argv) > 2 else os.path.join(lesson_dir, 'lessons.data.js')

    lessons = [parse_lesson(p) for p in lesson_files(lesson_dir)]
    text = json.dumps(lessons, ensure_ascii=False, separators=(',', ':'))
    packed = gzip.compress(text.encode('utf-8'), compresslevel=9, mtime=0)
    encoded = base64.b64encode(packed).decode('ascii')

    with open(output, 'w', encoding='ascii', newline='\n') as f:
        f.write('// Generated by build_lessons.py from the l*.json lesson files - do not edit.\n')
        f.write(f'window.LESSONS_GZ = "{encoded}";\n')

    cards = sum(len(l['cards']) for l in lessons)
    print(f'{len(lessons)} lessons, {cards} cards: JSON {len(text.encode("utf-8"))} bytes, '
          f'gzip {len(packed)} bytes, written {os.path.getsize(output)} bytes to {output}')


if __name__ == '__main__':
    main()
